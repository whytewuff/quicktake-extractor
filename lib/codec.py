def _s8(v):
    return v - 256 if v >= 128 else v


def _w16(v):                                       # store as C int16 (wrap)
    return ((v + 0x8000) & 0xFFFF) - 0x8000


def _cdiv(a, b):                                   # C integer division (toward zero)
    q = a // b
    if q < 0 and q * b != a:
        q += 1
    return q


class _BitReader:
    """dcraw getbithuff() over an in-memory stream (zero_after_ff = 0)."""
    def __init__(self, buf, pos):
        self.buf, self.pos = buf, pos
        self.bitbuf = self.vbits = 0

    def get(self, nbits, huff=None):
        if nbits > 25:
            return 0
        if nbits < 0:
            self.bitbuf = self.vbits = 0
            return 0
        if nbits == 0 or self.vbits < 0:
            return 0
        while self.vbits < nbits and self.pos < len(self.buf):
            self.bitbuf = ((self.bitbuf << 8) + self.buf[self.pos]) & 0xFFFFFFFF
            self.pos += 1
            self.vbits += 8
        c = (self.bitbuf << (32 - self.vbits)) & 0xFFFFFFFF
        c >>= (32 - nbits)
        if huff is not None:
            self.vbits -= huff[c] >> 8
            c = huff[c] & 0xFF
        else:
            self.vbits -= nbits
        return c


def _radc_tables():
    huff = [[0] * 256 for _ in range(19)]
    flat = []
    for i in range(0, len(_RADC_SRC), 2):
        nbits, val = _RADC_SRC[i], _RADC_SRC[i + 1]
        entry = ((nbits << 8) | (val & 0xFF)) & 0xFFFF
        flat.extend([entry] * (256 >> nbits))
    for idx, v in enumerate(flat):
        huff[idx // 256][idx % 256] = v
    for c in range(256):                           # tree 18 (kodak_cbpp != 243 -> s=3)
        huff[18][c] = (5 << 8) | ((c >> 3) << 3) | 4
    curve = [0] * 65536
    for i in range(2, 12, 2):
        lo, hi = _RADC_PT[i - 2], _RADC_PT[i]
        for c in range(lo, hi + 1):
            curve[c] = int((c - lo) / (hi - lo) * (_RADC_PT[i + 1] - _RADC_PT[i - 1])
                           + _RADC_PT[i - 1] + 0.5)
    return huff, curve


def _decode_radc(b, off, width, height, pack=True):
    huff, curve = _radc_tables()
    br = _BitReader(b, off)
    br.get(-1)
    raw = np.zeros((height, width), np.int32)
    rawv = raw
    buf = [[[2048] * 386 for _ in range(3)] for _ in range(3)]
    last = [16, 16, 16]
    mul = [0, 0, 0]
    W2 = width // 2

    def token(tree):
        return _s8(br.get(8, huff[tree]))

    def pred(bc, c, y, x):
        # codec uses asr (floor), not C division-toward-zero; they differ on
        # negative odd sums (dark noise) -- exposed by IMAGE12/IMAGE63
        if c:
            return (bc[y - 1][x] + bc[y][x + 1]) >> 1
        return (bc[y - 1][x + 1] + 2 * bc[y - 1][x] + bc[y][x + 1]) >> 2

    for row in range(0, height, 4):
        for c in range(3):
            mul[c] = br.get(6)
        for c in range(3):
            val = ((0x1000000 // last[c] + 0x7FF) >> 12) * mul[c]
            s = 10 if val > 65564 else 12
            x = (1 << (s - 1)) - 1
            val <<= (12 - s)
            bc = buf[c]
            for yy in range(3):
                ra = bc[yy]
                for i in range(386):
                    ra[i] = _w16((ra[i] * val + x) >> s)
            last[c] = mul[c]
            for r in range(0, (1 if c == 0 else 0) + 1):
                bc[1][W2] = bc[2][W2] = _w16(mul[c] << 7)
                tree, col = 1, W2
                while col > 0:
                    tree = token(tree)
                    if tree:
                        col -= 2
                        if tree == 8:
                            for y in (1, 2):
                                for xx in (col + 1, col):
                                    bc[y][xx] = _w16(br.get(8, huff[18]) * mul[c])
                        else:
                            for y in (1, 2):
                                for xx in (col + 1, col):
                                    bc[y][xx] = _w16(token(tree + 10) * 16 + pred(bc, c, y, xx))
                    else:
                        while True:
                            nreps = (token(9) + 1) if col > 2 else 1
                            rep = 0
                            while rep < 8 and rep < nreps and col > 0:
                                col -= 2
                                for y in (1, 2):
                                    for xx in (col + 1, col):
                                        bc[y][xx] = _w16(pred(bc, c, y, xx))
                                if rep & 1:
                                    step = token(10) << 4
                                    for y in (1, 2):
                                        for xx in (col + 1, col):
                                            bc[y][xx] = _w16(bc[y][xx] + step)
                                rep += 1
                            if nreps != 9:
                                break
                for y in range(2):
                    for xx in range(W2):
                        v = _cdiv(bc[y + 1][xx] << 4, mul[c])
                        if v < 0:
                            v = 0
                        if c:
                            rawv[row + y * 2 + c - 1, xx * 2 + 2 - c] = v
                        else:
                            rawv[row + r * 2 + y, xx * 2 + y] = v
                notc = 0 if c else 1
                bc[0][notc:] = bc[2][0:386 - notc]
        if not pack:
            continue                               # keep native luma/chroma layout
        for y in range(row, row + 4):
            ry = rawv[y]
            for x in range(width):
                if (x + y) & 1:
                    rr = x - 1 if x else x + 1
                    ss = x + 1 if x + 1 < width else x - 1
                    v = (ry[x] - 2048) * 2 + (ry[rr] + ry[ss]) // 2
                    ry[x] = v if v > 0 else 0
    if not pack:
        # native planes (pre-Bayer): green positions = luma, R pos = Cr, B pos = Cb
        return raw, 16383.0
    lut = np.array(curve, np.int32)
    return lut[np.clip(raw, 0, 65535)].astype(np.uint16), 16383.0


# Reciprocal output table from the original codec's `bd2c` (recip[s] = 65536/s),
# extracted verbatim from Inst 128.cdec. The codec emits each luma sample as
# clamp((coeff * recip[scale] + 0x7fff) >> 16, 0, 255) -- a *rounded* divide,
# where scale = the band's 6-bit `mul`. Our old (coeff<<4)//mul truncated, which
# is why we were 0.99999 (not 1.0) against the codec. Verified: reproduces the
# codec's own packed luma plane byte-for-byte (0/153600 mismatches on IMAGE04,
# via the m68k interpreter in codec_re/). See codec_re/QUICKTAKE_CODEC.md.
_RADC_RECIP = [0] + [round(65536 / s) for s in range(1, 64)]   # round, not floor


