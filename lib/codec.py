def _decode_qt100(b, off, width, height):
    import numpy as np
    H, W = height + 4, width + 4
    px = [[0x80] * W for _ in range(H)]
    br = _BitReader(b, off)
    br.get(-1)
    gstep, rstep = _QT100_GSTEP, _QT100_RSTEP
    for row in range(2, height + 2):
        val = 0
        col = 2 + (row & 1)
        while col < width + 2:
            val = ((px[row - 1][col - 1] + 2 * px[row - 1][col + 1]
                    + px[row][col - 2]) >> 2) + gstep[br.get(4)]
            val = 0 if val < 0 else 255 if val > 255 else val
            px[row][col] = val
            if col < 4:
                px[row][col - 2] = px[row + 1][~row & 1] = val
            if row == 2:
                px[row - 1][col + 1] = px[row - 1][col + 3] = val
            col += 2
        px[row][col] = val
    for rb in range(2):
        for row in range(2 + rb, height + 2, 2):
            col = 3 - (row & 1)
            while col < width + 2:
                if row < 4 or col < 4:
                    sharp = 2
                else:
                    v = (abs(px[row - 2][col] - px[row][col - 2])
                         + abs(px[row - 2][col] - px[row - 2][col - 2])
                         + abs(px[row][col - 2] - px[row - 2][col - 2]))
                    sharp = (0 if v < 4 else 1 if v < 8 else 2 if v < 16
                             else 3 if v < 32 else 4 if v < 48 else 5)
                val = ((px[row - 2][col] + px[row][col - 2]) >> 1) + rstep[sharp][br.get(2)]
                val = 0 if val < 0 else 255 if val > 255 else val
                px[row][col] = val
                if row < 4:
                    px[row - 2][col + 2] = val
                if col < 4:
                    px[row + 2][col - 2] = val
                col += 2
    for row in range(2, height + 2):
        col = 3 - (row & 1)
        while col < width + 2:
            val = ((px[row][col - 1] + (px[row][col] << 2) + px[row][col + 1]) >> 1) - 0x100
            px[row][col] = 0 if val < 0 else 255 if val > 255 else val
            col += 2
    lut = np.array(_QT100_CURVE, np.int32)
    out = np.array([[px[row + 2][col + 2] for col in range(width)] for row in range(height)],
                   np.int32)
    return lut[out].astype(np.uint16), 1023.0


def decode_cfa(qtk_path):
    """Decode a .qtk to (cfa uint16 HxW, sensor_white_level). No dcraw."""
    import struct
    b = _read_bytes(qtk_path)
    if b[0:4] not in (b"qktk", b"qktn"):
        raise RuntimeError("not a QuickTake .qtk file")
    height = struct.unpack(">H", b[544:546])[0]
    width = struct.unpack(">H", b[546:548])[0]
    data_offset = 738 if struct.unpack(">H", b[552:554])[0] == 30 else 736
    if height > width:                             # camera stored it rotated
        height, width = width, height
    if b[0:4] == b"qktk":
        return _decode_qt100(b, data_offset, width, height)
    return _decode_radc(b, data_offset, width, height)


def _read_bytes(path):
    with open(path, "rb") as fh:
        return fh.read()


