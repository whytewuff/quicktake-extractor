"""QuickTake raw codecs, in pure Python.

Two independent decoders live here:

1. `decode_cfa` -- a port of dcraw's QuickTake 100 (gradient predictor) and
   150 (Kodak RADC) decoders (Dave Coffin, public domain), verified
   byte-for-byte against `dcraw -D`. Returns a GRBG-packed mosaic for a
   conventional demosaic; used for QuickTake 100 files and raw renders.

2. `decode_codec_rgb` -- an instruction-faithful port of Apple's original
   QuickTake 150 codec (the QuickTime "QuickTake Image" 68k decompressor),
   reverse-engineered from its disassembly. Its RGB output is byte-identical
   to the original codec and hence to Apple PhotoFlash (validated
   pixel-perfect on 7/7 reference frames). Pipeline: entropy decode ->
   chroma recentre + luma-guided edge-directed refine -> demosaic + colour
   convert. Each stage is documented on its function; the reverse-engineering
   trail lives in codec_re/ (DECODE_PIPELINE.md, PLAN.md).

Note: the QuickTake sensor is not a plain Bayer array -- the stream encodes a
luma quincunx plus subsampled chroma; dcraw's GRBG mosaic is a repacking.
"""
